import sqlite3

db = sqlite3.connect("stock.db")

def patch(date_str, data, field):
    print(f"Patching {date_str} for {field}...")
    for code, amt in data:
        # Check if row exists
        row = db.execute("SELECT 1 FROM price_history WHERE stock_code=? AND date LIKE ?", (code, date_str+"%")).fetchone()
        if row:
            db.execute(f"UPDATE price_history SET {field}=? WHERE stock_code=? AND date LIKE ?", (amt, code, date_str+"%"))
        else:
            db.execute(f"INSERT INTO price_history (stock_code, date, open, high, low, close, volume, {field}) VALUES (?, ?, 0, 0, 0, 0, 0, ?)", (code, date_str, amt))
    db.commit()

